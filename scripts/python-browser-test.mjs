import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL ?? 'chrome', headless: true })
const base = process.env.APP_URL ?? 'http://127.0.0.1:5178'
try {
  const context = await browser.newContext()
  const page = await context.newPage()
  await page.goto(`${base}/code?exercise=review-time`)
  const run = () => page.getByRole('button', { name: 'Run code & check →', exact: true }).click()
  const finish = () => page.waitForFunction(() => document.querySelector('.coding-error') || document.querySelector('.coding-checks'), {}, { timeout: 70000 })
  await run(); await finish()
  assert.equal(await page.locator('.coding-error').count(), 0)
  assert.match(await page.locator('.coding-checks').innerText(), /Keep going/)
  await page.getByRole('button', { name: 'Hint & explanation', exact: true }).click()
  await page.getByRole('button', { name: 'Show worked solution', exact: true }).click()
  await page.getByRole('button', { name: 'Use solution in editor', exact: true }).click()
  await run(); await finish()
  assert.match(await page.locator('.coding-checks').innerText(), /All checks passed/)
  assert.match(await page.locator('.coding-output > pre').innerText(), /240/)
  assert.equal(await page.locator('iframe[title="Isolated Python execution"]').count(), 0)

  const draft = await page.locator('.cm-content').innerText()
  const runtimePattern = '**/pyodide/v314.0.7/full/pyodide.mjs'
  await context.route(runtimePattern, route => route.abort('failed'))
  await run(); await finish()
  assert.match(await page.locator('.coding-error').innerText(), /Your code has not run/)
  assert.ok(!(await page.locator('.coding-error').innerText()).includes('Check spelling'))
  assert.equal(await page.locator('.cm-content').innerText(), draft)
  await context.unroute(runtimePattern)
  await run(); await finish()
  assert.match(await page.locator('.coding-checks').innerText(), /All checks passed/)

  await page.locator('.cm-content').fill('print(1 / 0)')
  await run(); await finish()
  assert.match(await page.locator('.coding-error').innerText(), /ZeroDivisionError/)
  assert.ok(!(await page.locator('.coding-error').innerText()).includes('Your code has not run'))
  await page.locator('.cm-content').fill('while True:\n    pass')
  await run()
  await page.getByRole('button', { name: 'Stop', exact: true }).click()
  assert.equal(await page.locator('iframe[title="Isolated Python execution"]').count(), 0)
  await page.locator('.cm-content').fill('print(42)')
  await run(); await finish()
  assert.equal((await page.locator('.coding-output > pre').innerText()).trim(), '42')
  await page.reload()
  await page.locator('.cm-content').waitFor()
  assert.equal((await page.locator('.cm-content').innerText()).trim(), 'print(42)')

  // Inspect the real isolation boundary while a run is active.
  await page.locator('.cm-content').fill('while True:\n    pass')
  await run()
  const frame = page.locator('iframe[title="Isolated Python execution"]')
  assert.equal(await frame.getAttribute('sandbox'), 'allow-scripts')
  assert.match(await frame.getAttribute('srcdoc'), /worker-src data:/)
  assert.ok(!(await frame.getAttribute('srcdoc')).includes('allow-same-origin'))
  await page.getByRole('link', { name: 'Learning spaces', exact: true }).click()
  await frame.waitFor({ state: 'detached' })
  assert.equal(await page.locator('iframe[title="Isolated Python execution"]').count(), 0)
  console.log(`PASS in ${await browser.version()}: real sandbox startup, failed starter checks, successful solution/output, blocked-download diagnosis and retry, Python error, stop/retry, draft reload, opaque origin and navigation cleanup.`)
} finally { await browser.close() }
