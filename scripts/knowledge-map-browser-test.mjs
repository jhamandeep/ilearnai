import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright-core'

const base = process.env.APP_URL ?? 'http://127.0.0.1:5178'
const output = 'output/reviews/interactive-home-map'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
let totalNodes = 0, totalEdges = 0
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base)
  const home = page.locator('.home-knowledge-map')
  await home.scrollIntoViewIfNeeded()
  assert.equal(await page.locator('.knowledge-map').count(), 0, 'Homepage uses a background and map entry, not an embedded graph')
  await page.waitForFunction(() => document.querySelector('.section-links [aria-current="location"]')?.getAttribute('href') === '#knowledge-map')
  await home.getByRole('link', { name: 'Open the knowledge map' }).click()
  await page.waitForURL('**/knowledge-graph')
  const map = page.locator('.knowledge-map')
  await map.getByRole('button', { name: '2D view', exact: true }).click()
  await map.locator('.map-network [data-node-id]').first().waitFor()
  totalNodes = await map.locator('[data-node-id]').count()
  totalEdges = await map.locator('.map-network line').count()
  assert.ok(totalNodes > 300 && totalEdges > totalNodes, 'Dedicated map must contain the actual full graph')
  const ids = await map.locator('[data-node-id]').evaluateAll(elements => elements.map(element => element.dataset.nodeId).sort())
  await page.screenshot({ path: `${output}/home-map-overview.png` })
  await map.locator('.map-starters').getByRole('button', { name: 'Attention →', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.map-detail h3')?.textContent === 'Attention')
  assert.ok(await map.locator('.map-connections button').count() > 3)
  const zoomText = () => map.getByRole('status', { name: 'Map zoom' }).textContent()
  const beforeZoom = Number.parseInt(await zoomText())
  await map.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await page.waitForFunction(before => Number.parseInt(document.querySelector('.map-toolbar output').textContent) > before, beforeZoom)
  await map.getByRole('button', { name: 'Zoom out', exact: true }).click()
  const svg = map.locator('.topo-svg')
  await svg.focus()
  const transform = await map.locator('.map-network').getAttribute('transform')
  await page.keyboard.press('ArrowRight')
  assert.notEqual(await map.locator('.map-network').getAttribute('transform'), transform)
  const dot = map.locator('[data-node-id="concept:attention"]')
  await dot.scrollIntoViewIfNeeded()
  const box = await dot.boundingBox(), beforeDrag = await dot.getAttribute('transform')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 45, box.y + box.height / 2 + 25, { steps: 8 }); await page.mouse.up()
  assert.notEqual(await dot.getAttribute('transform'), beforeDrag, 'Dragging a node must update its position and lines')
  const surface = await svg.boundingBox(), beforePan = await map.locator('.map-network').getAttribute('transform')
  await page.mouse.move(surface.x + 15, surface.y + 20); await page.mouse.down(); await page.mouse.move(surface.x + 65, surface.y + 70, { steps: 6 }); await page.mouse.up()
  assert.notEqual(await map.locator('.map-network').getAttribute('transform'), beforePan, 'Background drag must pan the map')
  await map.getByRole('searchbox', { name: 'Find an idea' }).fill('Why attention replaced')
  await map.getByRole('list', { name: 'Matching ideas' }).getByRole('button').first().click()
  await page.waitForFunction(() => document.querySelector('.map-detail h3')?.textContent === 'Why attention replaced recurrence')
  assert.equal(await map.getByRole('link', { name: 'Open lesson →', exact: true }).getAttribute('href'), '/courses/ai-research/transformers/why-attention')
  await page.reload()
  await page.waitForURL('**/knowledge-graph?node=*')
  await page.getByRole('heading', { name: 'Knowledge map', exact: true, level: 1 }).waitFor()
  await page.waitForFunction(() => document.querySelector('.map-detail h3')?.textContent === 'Why attention replaced recurrence')
  await map.getByRole('button', { name: '2D view', exact: true }).click()
  assert.deepEqual(await map.locator('[data-node-id]').evaluateAll(elements => elements.map(element => element.dataset.nodeId).sort()), ids)
  await map.getByRole('combobox', { name: 'Filter knowledge map by course' }).selectOption('ai-research')
  await page.waitForFunction(total => document.querySelectorAll('[data-node-id]').length < total, totalNodes)
  for (const label of ['Concepts', 'Lessons', 'Papers', 'Labs', 'Terms']) await map.getByRole('checkbox', { name: label, exact: true }).uncheck()
  await map.getByText('No ideas are visible.', { exact: true }).waitFor()
  await map.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await page.waitForFunction(total => document.querySelectorAll('[data-node-id]').length === total, totalNodes)
  await map.getByRole('searchbox', { name: 'Find an idea' }).fill('no-such-topic-xyz')
  await map.getByText('No matching ideas. Try another word or clear the filters.', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await map.locator('.map-search-results').count(), 0)
  for (const width of [1440, 1100, 800, 600, 390, 320]) {
    await page.setViewportSize({ width, height: 1080 })
    await page.goto(base + '/knowledge-graph')
    await map.getByRole('button', { name: '2D view', exact: true }).click()
    await map.locator('[data-node-id]').first().waitFor()
    await map.getByRole('button', { name: 'Fit map', exact: true }).click()
    const dimensions = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }))
    assert.ok(dimensions.scroll <= width + 1, `${width}: page overflow ${dimensions.scroll}`)
    const clipped = await svg.evaluate(element => {
      const box = element.getBoundingClientRect()
      return [...element.querySelectorAll('[data-node-id]')].filter(node => { const matrix = node.getScreenCTM(); return matrix.e < box.left || matrix.e > box.right || matrix.f < box.top || matrix.f > box.bottom }).length
    })
    assert.equal(clipped, 0, `${width}: Fit map clipped nodes`)
    if (width === 1440 || width === 390 || width === 320) await page.screenshot({ path: `${output}/map-${width}.png` })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await map.locator('.map-starters').getByRole('button', { name: 'AI agents →', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.map-detail h3')?.textContent === 'Agents')
  assert.equal(await map.locator('.map-network').evaluate(element => getComputedStyle(element).animationName), 'none')
  const mobile = await browser.newContext({ viewport: { width: 390, height: 900 }, isMobile: true, hasTouch: true })
  const touchPage = await mobile.newPage()
  await touchPage.goto(base + '/knowledge-graph')
  await touchPage.getByRole('button', { name: '2D view', exact: true }).click()
  await touchPage.locator('.map-network').waitFor()
  await touchPage.locator('.map-stage').scrollIntoViewIfNeeded()
  const touchBox = await touchPage.locator('.map-stage').boundingBox()
  const cdp = await mobile.newCDPSession(touchPage)
  const y = Math.round(touchBox.y + touchBox.height / 2), x = Math.round(touchBox.x + touchBox.width / 2)
  const initialZoom = Number.parseInt(await touchPage.locator('.map-toolbar output').textContent())
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: x - 40, y, id: 1 }, { x: x + 40, y, id: 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - 75, y, id: 1 }, { x: x + 75, y, id: 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await touchPage.waitForFunction(before => Number.parseInt(document.querySelector('.map-toolbar output').textContent) > before, initialZoom)
  await mobile.close()
  assert.deepEqual(errors, [])
  await writeFile(`${output}/map-results.json`, JSON.stringify({ totalNodes, totalEdges, errors }, null, 2))
  console.log(`PASS: actual ${totalNodes}-node/${totalEdges}-connection graph reached from the homepage entry and retained on the map page; search, selection, deep links, filters, mouse drag, pan, zoom, keyboard, touch pinch, reduced motion and 320–1440px layouts.`)
} finally { await browser.close() }
