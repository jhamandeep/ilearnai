import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import { chromium } from 'playwright-core'
const base=process.env.APP_URL??'http://127.0.0.1:5178'
const output='output/reviews/video-explainer-20261028';await mkdir(output,{recursive:true})
const sample=JSON.parse(await readFile(new URL('../src/data/explainers/rag-sample.json',import.meta.url)))
assert.equal(sample.cues[0].start,0)
for(const [i,cue] of sample.cues.entries()) { assert.ok(cue.end>cue.start&&cue.text&&cue.title);if(i)assert.equal(cue.start,sample.cues[i-1].end) }
const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL??'chrome',headless:true})
const errors=[]
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000}})
 const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message))
 await page.goto(`${base}/preview/narrated-explainer`)
 await page.locator('.explainer-player').waitFor()
 await page.waitForFunction(()=>document.querySelector('audio').readyState>=1)
 const duration=await page.locator('audio').evaluate(a=>a.duration)
 assert.ok(Math.abs(duration-sample.duration)<.25,'Audio duration must match its recorded cue sheet')
 assert.ok(await page.locator('audio').evaluate(a=>a.paused&&a.currentTime===0),'No autoplay')
 await page.getByRole('button',{name:'Play narrated explainer',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('audio').currentTime>1)
 assert.equal(await page.locator('.explainer-player').getAttribute('data-playing'),'true')
 await page.getByRole('button',{name:'Pause explainer',exact:true}).click()
 const paused=await page.locator('audio').evaluate(a=>a.currentTime)
 await page.waitForTimeout(220)
 assert.equal(await page.locator('audio').evaluate(a=>a.currentTime),paused)
 const seek=page.getByRole('slider',{name:'Explainer timeline',exact:true})
 for(const cue of sample.cues) {
  await seek.fill(String(Math.round((cue.start+.8)*20)/20));await page.waitForFunction(id=>document.querySelector('.explainer-player').dataset.scene===id,cue.id)
  assert.ok((await page.locator('.explainer-captions').innerText()).includes(cue.text))
  assert.ok(Math.abs(await page.locator('audio').evaluate(a=>a.currentTime)-(cue.start+.8))<.08)
 }
 await page.getByRole('button',{name:'Mute narration',exact:true}).click();assert.ok(await page.locator('audio').evaluate(a=>a.muted))
 await page.getByRole('combobox',{name:'Explainer playback speed'}).selectOption('1.5');assert.equal(await page.locator('audio').evaluate(a=>a.playbackRate),1.5)
 await page.getByRole('button',{name:'Hide captions',exact:true}).click();assert.equal(await page.locator('.explainer-captions').getAttribute('aria-hidden'),'true')
 await page.getByRole('button',{name:'Show captions',exact:true}).click()
 await page.getByRole('button',{name:'Enter full screen',exact:true}).click()
 await page.waitForFunction(()=>!!document.fullscreenElement)
 await page.getByRole('button',{name:'Exit full screen',exact:true}).click()
 await page.waitForFunction(()=>!document.fullscreenElement)
 await seek.fill(String(Math.floor((duration-.25)*20)/20))
 await page.getByRole('button',{name:'Play explainer',exact:true}).click()
 await page.getByRole('button',{name:'Replay explainer',exact:true}).waitFor()
 await page.getByRole('button',{name:'Replay explainer',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('audio').currentTime>0&&document.querySelector('audio').currentTime<2&&!document.querySelector('audio').paused)
 await page.getByRole('button',{name:'Pause explainer',exact:true}).click()
 await seek.fill('12');await page.locator('.explainer-player').focus();await page.keyboard.press('ArrowLeft')
 assert.ok(Math.abs(await page.locator('audio').evaluate(a=>a.currentTime)-7)<.1)
 await page.getByRole('button',{name:'Restart explainer',exact:true}).click()
 assert.ok(await page.locator('audio').evaluate(a=>a.currentTime===0&&a.paused))
 // Keep a reference to the removed element to prove it was stopped on navigation.
 await page.getByRole('button',{name:'Play explainer',exact:true}).click()
 await page.evaluate(()=>{window.__sampleAudio=document.querySelector('audio')})
 await page.getByRole('link',{name:'Explore the retrieval chapter →',exact:true}).click()
 await page.locator('.explainer-player').waitFor({state:'detached'})
 assert.ok(await page.evaluate(()=>window.__sampleAudio.paused))

 for(const width of [1440,390,320]) {
  const p=await context.newPage();await p.setViewportSize({width,height:1000});p.on('pageerror',error=>errors.push(error.message))
  await p.goto(`${base}/preview/narrated-explainer`);await p.locator('.explainer-player').waitFor()
  await p.waitForFunction(()=>document.querySelector('audio').readyState>=1)
  await p.getByRole('slider',{name:'Explainer timeline',exact:true}).fill(String(Math.round((sample.cues.find(cue=>cue.id==='review').start+.8)*20)/20))
  await p.evaluate(()=>window.scrollTo(0,document.querySelector('.explainer-player').getBoundingClientRect().top+scrollY-90))
  await p.waitForTimeout(250)
  assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth),width,`No page overflow at ${width}`)
  const sizes=await p.locator('.explainer-player').evaluate(el=>({outer:el.getBoundingClientRect().width,inner:el.scrollWidth}))
  assert.ok(sizes.inner<=sizes.outer+1)
  await p.screenshot({path:`${output}/final-${width}.png`})
  await p.emulateMedia({reducedMotion:'reduce'})
  await p.getByRole('slider',{name:'Explainer timeline',exact:true}).fill(String(Math.round((sample.cues.find(cue=>cue.id==='question').start+.8)*20)/20))
  assert.equal(await p.locator('.explainer-player').getAttribute('data-scene'),'question')
  assert.ok(await p.locator('audio').evaluate(a=>a.paused))
  await p.close()
 }
 const failed=await browser.newContext();await failed.route(`**${sample.audio}`,route=>route.abort())
 const p=await failed.newPage();await p.goto(`${base}/preview/narrated-explainer`)
 await p.getByRole('alert').waitFor();assert.match(await p.getByRole('alert').innerText(),/recording could not load/)
 await failed.unroute(`**${sample.audio}`)
 await p.getByRole('button',{name:'Retry audio',exact:true}).click();await p.waitForFunction(()=>document.querySelector('audio').readyState>=1)
 await p.getByRole('button',{name:'Play narrated explainer',exact:true}).click();await p.waitForFunction(()=>document.querySelector('audio').currentTime>.2)
 assert.deepEqual(errors,[])
 console.log(`PASS Chrome ${browser.version()}: real AAC recording plays; no autoplay; synchronized cues/captions; pause, bidirectional seek, speed, mute, captions, fullscreen, end/replay, keyboard and navigation cleanup; desktop/mobile layout; reduced motion; blocked-audio retry. Audible voice quality is for user review.`)
} finally { await browser.close() }
